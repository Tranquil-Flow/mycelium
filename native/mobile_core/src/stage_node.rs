//! The phone's stage-only Router participant (plan §2, M4-phone): the
//! decisions a middle placement makes for every Router frame, without I/O.
//!
//! [`StageNode::on_frame`] takes one admitted Router frame from an
//! authenticated peer node and returns what the Python Router would decide
//! and send (`mycelium_router/relay.py` via `transports/iroh.py` `_dispatch`):
//!
//! - `ManifestLocked`: a locked path is registered (from the entry node with
//!   no source check, otherwise only as a confirmation from the final
//!   placement's node of a path already held); a pending tombstone from the
//!   entry, a cancelled attempt, an older attempt or a conflicting
//!   re-registration refuses it, and a refused registration is NOT
//!   acknowledged (`_NON_DELIVERED_SCOPED_ERRORS`);
//! - `HopHeader`: admission in `receive_hop`'s check order with its codes,
//!   the idempotency ledger (a retry gets the cached outcome with nothing run
//!   or re-sent; another payload under the same key is refused), the stage
//!   run, and then the forwarded hop to the next placement's node or the
//!   `FailureReport` to the entry node; always acknowledged;
//! - `PathCancellation`: only the entry node, for the registered request,
//!   attempt and topology; it forgets the path, its ledger entries and its
//!   runtime replay results (`released`); for a path not yet registered it
//!   records a pending tombstone charged to the sender; always acknowledged.
//!
//! Path tables follow the relay's model (`RELAY-PATH-TABLES.md`, revision 3,
//! `relay.py` after round 5) with phone-sized bounds ([`PHONE_BOUNDS`]):
//!
//! - I1 a live path id is bound to its owner (entry node, request); no other
//!   owner replaces it at any attempt;
//! - I2 every record is charged to the authenticated sender that created the
//!   path (always its entry here: a stage-only node has no provisional paths
//!   and a final-relayed manifest only confirms), and a pending cancellation
//!   to the peer that sent it;
//! - I3 tombstones are keyed (path id, owner) and bind only that owner; every
//!   phone release is the entry's own (cancellation) so it binds the owner up
//!   to its attempt; a high-water mark only rises;
//! - I4 a creator holds at most `quota_per_creator` records; at its quota it
//!   registers no new path id until its own records pass the relay-clock
//!   horizon; no other creator's record is ever touched for it;
//! - I5 eviction takes only records past the horizon, and the quota or slot
//!   check of a registration runs after its tombstone checks, so making room
//!   never evicts the record refusing that very registration;
//! - I6 there is no shared filter at all on the phone (no LOCAL authority);
//! - I7 at most `max_creators` slots (records or live paths); a new creator
//!   past the cap reclaims the least recently active idle slot (no live path,
//!   newest record past the horizon) or is refused; pending cancellations
//!   are bounded per source and in total (full: refused); live paths are
//!   bounded per creator and in total (full: the newcomer is refused, no live
//!   path is ever evicted).
//!
//! The tables survive [`StageNode::clear`] (a route change): a reassignment
//! never revives a cancelled attempt. The clock is the caller's monotonic
//! seconds ([`StageNode::on_frame_at`]); nothing in a frame moves it.
//!
//! A stage-only node registers only a path that places it in the middle
//! (never entry or final). `contracts/phone-stage-node-golden`, generated by
//! running the real Python Router as this node (with these bounds), pins
//! every decision and every sent byte (`tests/phone_stage_node.rs`).

use std::collections::{BTreeMap, BTreeSet, VecDeque};

use serde_json::Value;
use sha2::{Digest, Sha256};

use crate::stage_wire::{AdmittedHop, HopLedger, LedgerHit, LockedPath, idempotency_key};
use crate::wire::{self, Frame};

/// Relay-clock retention horizon of a tombstone record (as `relay.py`).
pub const TOMBSTONE_RETENTION_S: f64 = 600.0;
pub const LEDGER_CAPACITY: usize = 4096;

/// Path-table bounds. Every bound fails closed for whoever hits it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Bounds {
    /// Tombstone records one creator may hold.
    pub quota_per_creator: usize,
    /// Creator slots (records or live paths).
    pub max_creators: usize,
    /// Pending cancellations per authenticated source.
    pub pending_per_source: usize,
    /// Pending cancellations in total.
    pub pending_total: usize,
    /// Live registered paths in total; one creator holds at most
    /// `max_paths / max_creators` of them.
    pub max_paths: usize,
}

/// The phone's bounds (the relay's are 8192 / 64 / 4096 / 65536).
pub const PHONE_BOUNDS: Bounds = Bounds { quota_per_creator: 512, max_creators: 16, pending_per_source: 256, pending_total: 4096, max_paths: 256 };

/// One frame to send to a peer node.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Send {
    pub kind: &'static str,
    pub to: String,
    pub frame: Vec<u8>,
}

/// What the node decided for one frame.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Step {
    /// Acknowledge the transport delivery (`false`: the sender retries).
    pub ack: bool,
    /// Registration or cancellation accepted (those frames only).
    pub accepted: Option<bool>,
    /// `FORWARDED` / `FAILED` / `REJECTED` (hops only).
    pub disposition: Option<&'static str>,
    pub reason: String,
    /// The stage ran for this frame.
    pub executed: bool,
    pub sends: Vec<Send>,
    /// `(request_id, path_id)` whose runtime replay results must be released.
    pub released: Option<(String, String)>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Outcome {
    Forwarded,
    Failed(String),
}

struct Registered {
    path: LockedPath,
    body_digest: [u8; 32],
    /// The authenticated node that created the path (charged for it).
    creator: String,
}

/// The stage runner: given the path, the admitted hop and the inbound MYAC
/// payload, the outbound MYAC payload or a failure reason.
pub type Compute<'a> = dyn FnMut(&LockedPath, &AdmittedHop, &[u8]) -> Result<Vec<u8>, String> + 'a;

/// (entry node id, request id).
type Owner = (String, String);
type TombKey = (String, Owner);
/// (request, path, attempt, topology, source) of a cancellation that arrived
/// before its path.
type PendingKey = (String, String, i64, i64, String);

struct Tomb {
    attempt: i64,
    recorded_at: f64,
    creator: String,
}

pub struct StageNode {
    local: String,
    bounds: Bounds,
    paths: BTreeMap<String, Registered>,
    tombstones: BTreeMap<TombKey, Tomb>,
    /// creator -> (first-seen sequence, its records oldest first).
    by_creator: BTreeMap<String, (u64, VecDeque<TombKey>)>,
    creator_seq: u64,
    pending: BTreeSet<PendingKey>,
    /// Oldest first (a repeated cancellation moves to the end).
    pending_order: VecDeque<PendingKey>,
    pending_by_source: BTreeMap<String, usize>,
    /// Relay clock: the caller's monotonic seconds (never moves back).
    now: f64,
    ledger: HopLedger<Outcome>,
}

fn digest(v: &Value) -> [u8; 32] {
    Sha256::digest(crate::canonical::to_ascii_bytes(v).unwrap_or_default()).into()
}

impl StageNode {
    pub fn new(local_node_id: &str) -> Self {
        Self::with_bounds(local_node_id, PHONE_BOUNDS)
    }

    pub fn with_bounds(local_node_id: &str, bounds: Bounds) -> Self {
        Self {
            local: local_node_id.to_owned(),
            bounds,
            paths: BTreeMap::new(),
            tombstones: BTreeMap::new(),
            by_creator: BTreeMap::new(),
            creator_seq: 0,
            pending: BTreeSet::new(),
            pending_order: VecDeque::new(),
            pending_by_source: BTreeMap::new(),
            now: 0.0,
            ledger: HopLedger::new(LEDGER_CAPACITY),
        }
    }

    fn owner(path: &LockedPath) -> Owner {
        (path.entry_node_id.clone(), path.request_id.clone())
    }

    /// The highest attempt this owner cancelled under this path id.
    fn tombstone(&self, path_id: &str, owner: &Owner) -> Option<i64> {
        self.tombstones.get(&(path_id.to_owned(), owner.clone())).map(|t| t.attempt)
    }

    /// Record (or raise) the owner's tombstone, charged to `creator` (an
    /// existing record keeps its creator), then trim that creator's own
    /// records past the horizon down to its quota.
    fn record_tombstone(&mut self, path_id: &str, owner: Owner, attempt: i64, creator: &str) {
        let key = (path_id.to_owned(), owner);
        let now = self.now;
        let charged = match self.tombstones.get_mut(&key) {
            Some(t) => {
                t.attempt = t.attempt.max(attempt);
                t.recorded_at = now;
                t.creator.clone()
            }
            None => {
                self.tombstones.insert(key.clone(), Tomb { attempt, recorded_at: now, creator: creator.to_owned() });
                creator.to_owned()
            }
        };
        if !self.by_creator.contains_key(&charged) {
            self.creator_seq += 1;
            self.by_creator.insert(charged.clone(), (self.creator_seq, VecDeque::new()));
        }
        let records = &mut self.by_creator.get_mut(&charged).unwrap().1;
        records.retain(|k| *k != key);
        records.push_back(key);
        self.prune_creator(&charged, self.bounds.quota_per_creator);
    }

    /// Drop one record (it bound only its owner, and is past the horizon).
    fn evict(&mut self, key: &TombKey) {
        if let Some(t) = self.tombstones.remove(key)
            && let Some((_, records)) = self.by_creator.get_mut(&t.creator)
        {
            records.retain(|k| k != key);
            if records.is_empty() {
                self.by_creator.remove(&t.creator);
            }
        }
    }

    /// Evict a creator's own records past the horizon while it holds more
    /// than `limit`; never another creator's, never a young one.
    fn prune_creator(&mut self, creator: &str, limit: usize) {
        loop {
            let Some((_, records)) = self.by_creator.get(creator) else {
                return;
            };
            if records.len() <= limit {
                return;
            }
            let oldest = records.front().cloned().unwrap();
            let at = self.tombstones.get(&oldest).map_or(self.now, |t| t.recorded_at);
            if self.now - at < TOMBSTONE_RETENTION_S {
                return;
            }
            self.evict(&oldest);
        }
    }

    fn live_creators(&self) -> BTreeSet<&str> {
        self.paths.values().map(|r| r.creator.as_str()).collect()
    }

    /// Creators holding a slot: records or a live path (never this node).
    fn creator_slots(&self) -> BTreeSet<String> {
        let mut slots: BTreeSet<String> = self.by_creator.keys().cloned().collect();
        slots.extend(self.live_creators().into_iter().map(str::to_owned));
        slots.remove(&self.local);
        slots
    }

    /// Free the least recently active idle slot: a creator with no live path
    /// whose newest record is past the horizon (ties: the earliest creator).
    fn reclaim_idle_slot(&mut self) -> bool {
        let live = self.live_creators();
        let mut idle: Option<(f64, u64, String)> = None;
        for (creator, (seq, records)) in &self.by_creator {
            if *creator == self.local || live.contains(creator.as_str()) || records.is_empty() {
                continue;
            }
            let newest = records.iter().map(|k| self.tombstones.get(k).map_or(self.now, |t| t.recorded_at)).fold(f64::NEG_INFINITY, f64::max);
            if self.now - newest < TOMBSTONE_RETENTION_S {
                continue;
            }
            if idle.as_ref().is_none_or(|(at, s, _)| newest < *at || (newest == *at && seq < s)) {
                idle = Some((newest, *seq, creator.clone()));
            }
        }
        let Some((_, _, creator)) = idle else {
            return false;
        };
        let records: Vec<TombKey> = self.by_creator.get(&creator).map(|(_, r)| r.iter().cloned().collect()).unwrap_or_default();
        for key in records {
            self.evict(&key);
        }
        true
    }

    /// Fail closed for this creator only: at its quota (after evicting its
    /// own records past the horizon), or as a new creator past the cap when
    /// no idle slot can be reclaimed.
    fn creator_may_register(&mut self, creator: &str) -> bool {
        let quota = self.bounds.quota_per_creator;
        if self.by_creator.get(creator).is_some_and(|(_, r)| r.len() >= quota) {
            self.prune_creator(creator, quota - 1);
            if self.by_creator.get(creator).is_some_and(|(_, r)| r.len() >= quota) {
                return false;
            }
        }
        if creator == self.local {
            return true;
        }
        let slots = self.creator_slots();
        if slots.contains(creator) || slots.len() < self.bounds.max_creators {
            return true;
        }
        self.reclaim_idle_slot()
    }

    /// Live paths: the newcomer is refused at the total bound or at its own
    /// share; no live path is ever evicted for it.
    fn creator_may_hold_another_path(&self, creator: &str) -> bool {
        let share = (self.bounds.max_paths / self.bounds.max_creators.max(1)).max(1);
        self.paths.len() < self.bounds.max_paths && self.paths.values().filter(|r| r.creator == creator).count() < share
    }

    /// [`on_frame`](Self::on_frame) at the caller's monotonic clock in seconds
    /// (the tombstone horizon is measured with it; it never moves back).
    pub fn on_frame_at(&mut self, now: f64, from: &str, frame: &Frame, compute: &mut Compute<'_>) -> Step {
        self.now = self.now.max(now);
        self.on_frame(from, frame, compute)
    }

    fn forget_pending(&mut self, key: &PendingKey) {
        if self.pending.remove(key) {
            self.pending_order.retain(|k| k != key);
            if let Some(count) = self.pending_by_source.get_mut(&key.4) {
                *count -= 1;
                if *count == 0 {
                    self.pending_by_source.remove(&key.4);
                }
            }
        }
    }

    pub fn path(&self, path_id: &str) -> Option<&LockedPath> {
        self.paths.get(path_id).map(|r| &r.path)
    }

    /// Every peer node of every registered path (for the transport peer set).
    pub fn peer_nodes(&self) -> BTreeSet<String> {
        self.paths.values().flat_map(|r| r.path.hops.iter().map(|h| h.node_id.clone())).filter(|n| *n != self.local).collect()
    }

    /// A route change: forget the live paths and the hop ledger. Tombstones
    /// and pending cancellations are kept (fail closed): a reassignment never
    /// revives a cancelled attempt.
    pub fn clear(&mut self) {
        self.paths.clear();
        self.ledger = HopLedger::new(LEDGER_CAPACITY);
    }

    pub fn on_frame(&mut self, from: &str, frame: &Frame, compute: &mut Compute<'_>) -> Step {
        match frame.message_type.as_str() {
            "ManifestLocked" => self.manifest_locked(from, &frame.body),
            "HopHeader" => self.hop(from, &frame.body, &frame.payload, compute),
            "PathCancellation" => self.cancellation(from, &frame.body),
            // A stage-only node takes part in nothing else.
            _ => Step { ack: false, reason: "message_type_unsupported_by_stage".into(), ..Step::default() },
        }
    }

    /// `relay.py` `_consume_pending_cancellation_locked`: `Some(true)` when
    /// the entry's own pending cancellation refuses this registration.
    fn consume_pending(&mut self, path: &LockedPath, owner: &Owner) -> bool {
        let key = (path.request_id.clone(), path.path_id.clone(), path.path_attempt, path.topology_version, path.entry_node_id.clone());
        let matched = self.pending.contains(&key);
        if matched && !self.creator_may_register(&path.entry_node_id) {
            // The entry has no slot for the record: keep its pending
            // cancellation (bounded per source) so the attempt stays refused.
            return true;
        }
        let of_path: Vec<PendingKey> = self.pending_order.iter().filter(|k| k.1 == path.path_id).cloned().collect();
        for old in &of_path {
            self.forget_pending(old);
        }
        if matched {
            let entry = path.entry_node_id.clone();
            self.record_tombstone(&path.path_id, owner.clone(), path.path_attempt, &entry);
        }
        matched
    }

    fn manifest_locked(&mut self, from: &str, body: &Value) -> Step {
        let refused = |reason: &str| Step { ack: false, accepted: Some(false), reason: reason.into(), ..Step::default() };
        let rejected = || refused("manifest_registration_rejected");
        let Ok(path) = LockedPath::from_manifest_locked(body) else {
            return refused("invalid_manifest_locked");
        };
        // transports/iroh.py: a manifest from the entry registers without a
        // source; any other source must be the final placement's node.
        let final_node = &path.hops[path.hops.len() - 1].node_id;
        if path.entry_node_id.is_empty() || (from != path.entry_node_id && from != final_node) {
            return rejected();
        }
        if path.local_hop(&self.local).is_err() {
            return rejected();
        }
        // I2: the creator is the authenticated sender, placed on the path
        // (entry or final placement, checked above).
        let creator = from.to_owned();
        let existing = self.paths.contains_key(&path.path_id);
        // A manifest relayed by the final placement only confirms a path this
        // node already holds from the entry; it never creates one.
        if from != path.entry_node_id && !existing {
            return rejected();
        }
        let owner = Self::owner(&path);
        // I1: a live path id stays bound to its owner whatever the attempt.
        if self.paths.get(&path.path_id).is_some_and(|e| Self::owner(&e.path) != owner) {
            return rejected();
        }
        // relay.py order: pending, tombstones, then the creator's quota/slot
        // (I5: making room never evicts the record refusing this frame).
        if self.consume_pending(&path, &owner) {
            return rejected();
        }
        if self.tombstone(&path.path_id, &owner).is_some_and(|max| path.path_attempt <= max) {
            return rejected();
        }
        if !existing && !self.creator_may_register(&creator) {
            return rejected();
        }
        let body_digest = digest(&body["manifest"]);
        let build_digest = digest(&body["build"]);
        let combined: [u8; 32] = Sha256::digest([body_digest, build_digest].concat()).into();
        // An older attempt never replaces a newer one; the same attempt only
        // re-registers identically (a sender retry).
        if let Some(e) = self.paths.get(&path.path_id) {
            if path.path_attempt < e.path.path_attempt || (path.path_attempt == e.path.path_attempt && combined != e.body_digest) {
                return rejected();
            }
            if path.path_attempt == e.path.path_attempt {
                return Step { ack: true, accepted: Some(true), ..Step::default() };
            }
        }
        if !existing && !self.creator_may_hold_another_path(&creator) {
            return rejected();
        }
        let path_id = path.path_id.clone();
        // A newer attempt of the same owner retires the older one, charged to
        // the path's creator.
        let creator = match self.paths.remove(&path_id) {
            Some(old) => {
                self.record_tombstone(&path_id, owner, old.path.path_attempt, &old.creator);
                old.creator
            }
            None => creator,
        };
        self.paths.insert(path_id, Registered { path, body_digest: combined, creator });
        Step { ack: true, accepted: Some(true), ..Step::default() }
    }

    fn hop(&mut self, from: &str, header: &Value, payload: &[u8], compute: &mut Compute<'_>) -> Step {
        let rejected = |reason: &str| Step { ack: true, disposition: Some("REJECTED"), reason: reason.into(), ..Step::default() };
        let text = |k: &str| header[k].as_str().unwrap_or("");
        let int = |k: &str| header[k].as_i64().unwrap_or(i64::MIN);
        let key = idempotency_key(text("request_id"), text("path_id"), int("path_attempt"), text("phase"), int("token_index"), int("hop_index"));
        if header["idempotency_key"] != key.as_str() {
            return rejected("invalid_idempotency_key");
        }
        let Some(registered) = self.paths.get(text("path_id")) else {
            return rejected("unknown_path");
        };
        let path = registered.path.clone();
        let hop = match path.admit(&self.local, header, from, payload) {
            Ok(hop) => hop,
            Err(e) => return rejected(e.0),
        };
        match self.ledger.check(&hop) {
            Some(LedgerHit::Conflict) => return rejected("idempotency_payload_mismatch"),
            Some(LedgerHit::Cached(outcome)) => {
                return match outcome {
                    Outcome::Forwarded => Step { ack: true, disposition: Some("FORWARDED"), ..Step::default() },
                    Outcome::Failed(reason) => Step { ack: true, disposition: Some("FAILED"), reason, ..Step::default() },
                };
            }
            None => {}
        }
        let (outcome, send) = match compute(&path, &hop, payload) {
            Ok(out) => match path.forward_header(&hop, header) {
                Ok((body, next)) => match wire::encode_frame("HopHeader", &body, &out) {
                    Ok(frame) => (Outcome::Forwarded, Send { kind: "HopHeader", to: next.node_id.clone(), frame }),
                    Err(e) => self.failure(&path, &hop, e.0),
                },
                Err(e) => self.failure(&path, &hop, e.0),
            },
            Err(reason) => self.failure(&path, &hop, &reason),
        };
        self.ledger.record(&hop, outcome.clone());
        let (disposition, reason) = match &outcome {
            Outcome::Forwarded => ("FORWARDED", String::new()),
            Outcome::Failed(r) => ("FAILED", r.clone()),
        };
        Step { ack: true, disposition: Some(disposition), reason, executed: true, sends: vec![send], ..Step::default() }
    }

    fn failure(&self, path: &LockedPath, hop: &AdmittedHop, reason: &str) -> (Outcome, Send) {
        let body = path.failure_report(hop, &self.local, reason);
        let frame = wire::encode_frame("FailureReport", &body, b"").unwrap_or_default();
        (Outcome::Failed(reason.to_owned()), Send { kind: "FailureReport", to: path.entry_node_id.clone(), frame })
    }

    fn cancellation(&mut self, from: &str, body: &Value) -> Step {
        let answer = |accepted: bool| Step { ack: true, accepted: Some(accepted), ..Step::default() };
        let (Some(request_id), Some(path_id), Some(attempt), Some(topology)) =
            (body["request_id"].as_str(), body["path_id"].as_str(), body["path_attempt"].as_i64(), body["topology_version"].as_i64())
        else {
            return answer(false);
        };
        if request_id.is_empty() || path_id.is_empty() || from.is_empty() {
            return answer(false);
        }
        let Some(registered) = self.paths.get(path_id) else {
            // The claimed owner of an unknown path is (source, request).
            if self.tombstone(path_id, &(from.to_owned(), request_id.to_owned())).is_some_and(|max| attempt <= max) {
                return answer(false);
            }
            let key = (request_id.to_owned(), path_id.to_owned(), attempt, topology, from.to_owned());
            if self.pending.contains(&key) {
                self.pending_order.retain(|k| *k != key);
                self.pending_order.push_back(key);
                return answer(true);
            }
            if self.pending_by_source.get(from).copied().unwrap_or(0) >= self.bounds.pending_per_source {
                // A source displaces only its own oldest pending tombstone.
                if let Some(old) = self.pending_order.iter().find(|k| k.4 == from).cloned() {
                    self.forget_pending(&old);
                }
            } else if self.pending.len() >= self.bounds.pending_total {
                return answer(false);
            }
            self.pending.insert(key.clone());
            self.pending_order.push_back(key);
            *self.pending_by_source.entry(from.to_owned()).or_insert(0) += 1;
            return answer(true);
        };
        if !registered.path.cancellation_matches(body, from) {
            return answer(false);
        }
        let owner = Self::owner(&registered.path);
        let removed = self.paths.remove(path_id).unwrap();
        // The entry's own release: binds its owner up to this attempt (I3),
        // charged to the path's creator.
        self.record_tombstone(path_id, owner, attempt, &removed.creator);
        self.ledger.forget_path(request_id, path_id);
        Step { ack: true, accepted: Some(true), released: Some((request_id.to_owned(), path_id.to_owned())), ..Step::default() }
    }
}

