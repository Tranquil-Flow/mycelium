//! The Router-wire rules a stage-only (middle) node must follow, ported from
//! `mycelium_router/relay.py` without I/O: learn a locked path from
//! `ManifestLocked`, admit a `HopHeader` exactly as `RelayEngine.receive_hop`
//! does (same checks, same order, same refusal codes), derive the work item's
//! KV position, build the forwarded header for the next hop, originate a
//! `FailureReport`, accept the entry's `PathCancellation`, and keep the
//! idempotency ledger that turns a sender retry into the cached result.
//!
//! The cross-language golden vectors in `contracts/phone-stage-wire-golden`
//! (generated by running the real Python Router as the middle node) pin every
//! rule here; `tests/phone_stage_wire.rs` replays them.

use std::collections::{BTreeMap, VecDeque};

use serde_json::{Value, json};
use sha2::{Digest, Sha256};

#[derive(Debug, Clone, PartialEq, Eq, thiserror::Error)]
#[error("{0}")]
pub struct StageWireError(pub &'static str);

fn fail<T>(code: &'static str) -> Result<T, StageWireError> {
    Err(StageWireError(code))
}

/// `hop_idempotency_key` (`mycelium_router/idempotency.py`).
pub fn idempotency_key(request_id: &str, path_id: &str, path_attempt: i64, phase: &str, token_index: i64, hop_index: i64) -> String {
    format!("{request_id}:{path_id}:{path_attempt}:{phase}:{token_index}:{hop_index}")
}

/// `payload_fingerprint` of a bytes payload: `sha256(b"y" + u64 BE len + bytes)`.
pub fn payload_fingerprint(payload: &[u8]) -> String {
    let mut h = Sha256::new();
    h.update(b"y");
    h.update((payload.len() as u64).to_be_bytes());
    h.update(payload);
    hex::encode(h.finalize())
}

/// One placement of the locked path, in hop order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RouteHop {
    pub placement_id: String,
    pub node_id: String,
    pub runtime_backend: String,
}

/// What a middle node keeps from `ManifestLocked`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct LockedPath {
    pub request_id: String,
    pub path_id: String,
    pub path_attempt: i64,
    pub topology_version: i64,
    pub hops: Vec<RouteHop>,
    pub entry_node_id: String,
    pub prompt_length: usize,
    pub hidden_size: usize,
}

/// A hop's structured identity (`idempotency.hop_identity`): the fields its
/// idempotency key joins with ':'. Ids may contain ':', so per-hop state is
/// never keyed by the joined string.
pub type HopIdentity = (String, String, i64, String, i64, usize);

/// A hop the node admitted: what to run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AdmittedHop {
    pub request_id: String,
    pub path_id: String,
    pub path_attempt: i64,
    pub phase: String,
    pub token_index: i64,
    pub hop_index: usize,
    pub placement_id: String,
    pub idempotency_key: String,
    /// `RelayEngine._kv_position`.
    pub position: usize,
    pub payload_fingerprint: String,
}

fn s<'v>(v: &'v Value, code: &'static str) -> Result<&'v str, StageWireError> {
    v.as_str().ok_or(StageWireError(code))
}

fn i(v: &Value, code: &'static str) -> Result<i64, StageWireError> {
    v.as_i64().ok_or(StageWireError(code))
}

impl LockedPath {
    /// From a decoded `ManifestLocked` body. The entry node is the node of the
    /// first ordered hop (`transports/iroh.py` registers it the same way).
    pub fn from_manifest_locked(body: &Value) -> Result<Self, StageWireError> {
        let code = "invalid_manifest_locked";
        let manifest = &body["manifest"];
        let build = &body["build"];
        let graph = &build["graph"];
        let request = &build["request"];
        let mut placements = BTreeMap::new();
        for stage in graph["stages"].as_array().ok_or(StageWireError(code))? {
            for p in stage["placements"].as_array().ok_or(StageWireError(code))? {
                placements.insert(
                    s(&p["placement_id"], code)?.to_owned(),
                    (s(&p["node_id"], code)?.to_owned(), s(&p["runtime_backend"], code)?.to_owned()),
                );
            }
        }
        let hops = manifest["ordered_hops"]
            .as_array()
            .filter(|h| !h.is_empty())
            .ok_or(StageWireError(code))?
            .iter()
            .map(|h| {
                let pid = s(&h["placement_id"], code)?;
                let (node, backend) = placements.get(pid).ok_or(StageWireError("unknown_placement"))?;
                Ok(RouteHop { placement_id: pid.to_owned(), node_id: node.clone(), runtime_backend: backend.clone() })
            })
            .collect::<Result<Vec<_>, StageWireError>>()?;
        let path = Self {
            request_id: s(&manifest["request_id"], code)?.to_owned(),
            path_id: s(&manifest["path_id"], code)?.to_owned(),
            path_attempt: i(&manifest["path_attempt"], code)?,
            topology_version: i(&manifest["topology_version"], code)?,
            entry_node_id: hops[0].node_id.clone(),
            prompt_length: request["prompt_token_ids"].as_array().ok_or(StageWireError(code))?.len(),
            hidden_size: graph["hidden_size"].as_u64().ok_or(StageWireError(code))? as usize,
            hops,
        };
        if body["request_id"] != path.request_id.as_str()
            || body["path_id"] != path.path_id.as_str()
            || body["path_attempt"].as_i64() != Some(path.path_attempt)
            || request["request_id"] != path.request_id.as_str()
            || graph["topology_version"].as_i64() != Some(path.topology_version)
        {
            return fail(code);
        }
        Ok(path)
    }

    /// This node's hop: it must hold exactly one placement, and a stage-only
    /// node is never the entry (hop 0) nor the final hop.
    pub fn local_hop(&self, local_node_id: &str) -> Result<usize, StageWireError> {
        let mine: Vec<usize> = self.hops.iter().enumerate().filter(|(_, h)| h.node_id == local_node_id).map(|(i, _)| i).collect();
        match mine.as_slice() {
            [] => fail("destination_not_local"),
            [i] if *i == 0 || *i + 1 == self.hops.len() => fail("stage_only_node_not_middle"),
            [i] => Ok(*i),
            _ => fail("stage_only_node_multiple_placements"),
        }
    }

    /// `RelayEngine.receive_hop` admission for a middle node, in Python's order.
    pub fn admit(&self, local_node_id: &str, header: &Value, source_node_id: &str, payload: &[u8]) -> Result<AdmittedHop, StageWireError> {
        let code = "invalid_hop_header";
        let (request_id, path_id) = (s(&header["request_id"], code)?, s(&header["path_id"], code)?);
        let (attempt, phase) = (i(&header["path_attempt"], code)?, s(&header["phase"], code)?);
        let (token_index, hop_index) = (i(&header["token_index"], code)?, i(&header["hop_index"], code)?);
        if header["idempotency_key"] != idempotency_key(request_id, path_id, attempt, phase, token_index, hop_index).as_str() {
            return fail("invalid_idempotency_key");
        }
        if path_id != self.path_id {
            return fail("unknown_path");
        }
        if attempt != self.path_attempt || request_id != self.request_id {
            return fail("stale_path_attempt");
        }
        if header["topology_version"].as_i64() != Some(self.topology_version) {
            return fail("topology_version_mismatch");
        }
        if hop_index < 0 || hop_index as usize >= self.hops.len() {
            return fail("invalid_hop_index");
        }
        let h = hop_index as usize;
        if header["destination_placement_id"] != self.hops[h].placement_id.as_str() {
            return fail("manifest_hop_mismatch");
        }
        let source = header["source_placement_id"].as_str().unwrap_or("\u{0}");
        let valid_source = if h == 0 {
            source.is_empty() || (phase == "DECODE" && source == self.hops[self.hops.len() - 1].placement_id)
        } else {
            source == self.hops[h - 1].placement_id
        };
        if !valid_source {
            return fail("source_placement_mismatch");
        }
        if h == 0 {
            if source_node_id != self.entry_node_id {
                return fail("entry_node_mismatch");
            }
        } else if self.hops[h - 1].node_id != source_node_id {
            return fail("source_node_mismatch");
        }
        if self.hops[h].node_id != local_node_id {
            return fail("destination_not_local");
        }
        let position = match phase {
            "PREFILL" | "RECOVERY_PREFILL" => 0,
            "DECODE" => usize::try_from(self.prompt_length as i64 + token_index - 1).map_err(|_| StageWireError(code))?,
            // Chunked prefill needs stage-local KV; a replay-only stage refuses it.
            _ => return fail("phase_unsupported_by_stage"),
        };
        Ok(AdmittedHop {
            request_id: request_id.to_owned(),
            path_id: path_id.to_owned(),
            path_attempt: attempt,
            phase: phase.to_owned(),
            token_index,
            hop_index: h,
            placement_id: self.hops[h].placement_id.clone(),
            idempotency_key: header["idempotency_key"].as_str().unwrap().to_owned(),
            position,
            payload_fingerprint: payload_fingerprint(payload),
        })
    }

    /// The `HopHeader` body for the next hop (relay.py forward block).
    pub fn forward_header(&self, hop: &AdmittedHop, inbound: &Value) -> Result<(Value, &RouteHop), StageWireError> {
        let next = self.hops.get(hop.hop_index + 1).ok_or(StageWireError("no_next_hop"))?;
        let next_index = hop.hop_index as i64 + 1;
        let body = json!({
            "request_id": self.request_id,
            "path_id": self.path_id,
            "path_attempt": self.path_attempt,
            "phase": hop.phase,
            "token_index": hop.token_index,
            "hop_index": next_index,
            "source_placement_id": hop.placement_id,
            "destination_placement_id": next.placement_id,
            "topology_version": self.topology_version,
            "idempotency_key": idempotency_key(&self.request_id, &self.path_id, self.path_attempt, &hop.phase, hop.token_index, next_index),
            "prefill_chunk_token_count": inbound["prefill_chunk_token_count"].as_i64().unwrap_or(0),
        });
        Ok((body, next))
    }

    /// The `FailureReport` body the stage sends to the entry node when its runtime fails.
    pub fn failure_report(&self, hop: &AdmittedHop, local_node_id: &str, reason: &str) -> Value {
        json!({
            "request_id": self.request_id,
            "path_id": self.path_id,
            "path_attempt": self.path_attempt,
            "token_index": hop.token_index,
            "scope": "PLACEMENT",
            "reason": reason,
            "placement_id": hop.placement_id,
            "edge_id": "",
            "node_id": local_node_id,
        })
    }

    /// The entry's `PathCancellation` for this path attempt.
    pub fn cancellation_matches(&self, body: &Value, source_node_id: &str) -> bool {
        source_node_id == self.entry_node_id
            && body["request_id"] == self.request_id.as_str()
            && body["path_id"] == self.path_id.as_str()
            && body["path_attempt"].as_i64() == Some(self.path_attempt)
            && body["topology_version"].as_i64() == Some(self.topology_version)
    }
}

/// What a completed hop left behind, for a sender retry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LedgerHit<T> {
    /// Same key, same payload: return the cached outcome, do not re-execute.
    Cached(T),
    /// Same key, different payload: refuse.
    Conflict,
}

/// Bounded idempotency ledger keyed by idempotency key, remembering the
/// payload fingerprint and the outcome (e.g. the forwarded frame bytes).
impl AdmittedHop {
    pub fn identity(&self) -> HopIdentity {
        (self.request_id.clone(), self.path_id.clone(), self.path_attempt, self.phase.clone(), self.token_index, self.hop_index)
    }
}

pub struct HopLedger<T> {
    capacity: usize,
    order: VecDeque<HopIdentity>,
    entries: BTreeMap<HopIdentity, (String, T)>,
}

impl<T: Clone> HopLedger<T> {
    pub fn new(capacity: usize) -> Self {
        Self { capacity: capacity.max(1), order: VecDeque::new(), entries: BTreeMap::new() }
    }

    pub fn check(&self, hop: &AdmittedHop) -> Option<LedgerHit<T>> {
        self.entries.get(&hop.identity()).map(|(fp, outcome)| {
            if *fp == hop.payload_fingerprint { LedgerHit::Cached(outcome.clone()) } else { LedgerHit::Conflict }
        })
    }

    pub fn record(&mut self, hop: &AdmittedHop, outcome: T) {
        let key = hop.identity();
        if self.entries.insert(key.clone(), (hop.payload_fingerprint.clone(), outcome)).is_none() {
            self.order.push_back(key);
        }
        while self.order.len() > self.capacity {
            if let Some(old) = self.order.pop_front() {
                self.entries.remove(&old);
            }
        }
    }

    /// Forget a path's hops (cancellation, new assignment, route drop).
    pub fn forget_path(&mut self, request_id: &str, path_id: &str) {
        let of_path = |k: &HopIdentity| k.0 == request_id && k.1 == path_id;
        self.entries.retain(|k, _| !of_path(k));
        self.order.retain(|k| !of_path(k));
    }

    pub fn len(&self) -> usize {
        self.entries.len()
    }

    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }
}
