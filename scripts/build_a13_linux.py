"""Build the A13 Linux self-installing per-user bundle (owner_private_media).

Same split as ``scripts/build_a13_windows.py`` (PyInstaller cannot cross-build):

  frozen-input  (any host, offline)   stage the app's source closure + a
                                      deterministic PyInstaller spec, unsigned
  [run day, Ubuntu 24.04 build host]  pyinstaller mycelium-linux.spec, add the
                                      sidecar and cloudflared (linux builds)
  finalize      (any host, offline)   digest the frozen tree, sign the manifest,
                                      lay out the bundle, deterministic tar.gz

The bundle installs per user (``mycelium/mycelium --install``; see
``mycelium_a13_linux.installer``).  Linux has no OS code-signing layer: the
pinned Ed25519 release key in the signed manifest is the publisher identity.
The signing key is NEVER read from argv, environment, stdout, or any artifact:
pass its path with ``--signing-key-file`` (32 raw Ed25519 private-key bytes).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from mycelium_a13_packaging import build as _build  # noqa: E402

_APP_TREE_MARKERS = (
    "mycelium_a13_linux/__init__.py",
    "mycelium_a13_linux/installer.py",
    "mycelium_a13_linux/package_manifest.py",
    "mycelium_a13_linux/install_source.py",
    "mycelium_a13_macos/__main__.py",
    "mycelium_service_package.py",
)
_FROZEN_SEEDS = (
    "mycelium_a13_macos",
    "mycelium_a13_linux",
    "mycelium_service_package.py",
    "mycelium_service_runner.py",
)
_FROZEN_DATA = ("mycelium_a13_macos/web",)
FROZEN_REQUIRED = (
    "mycelium",
    "_internal/mycelium_a13_macos/native/mycelium-iroh-sidecar",
    "_internal/mycelium_a13_macos/native/cloudflared",
)
PYINSTALLER_PIN = "6.22.3"
LINUX_PYTHON = "3.14"
BUILD_HOST = "ubuntu-24.04"  # the admitted floor: the bundle runs on this glibc (2.39) and newer
FROZEN_INPUT_PROTOCOL = "mycelium.a13_linux_frozen_input.v1"
_CHANNEL = "owner_private_media"
_SIGNER_ENDPOINT_ID = "mycelium-linux-release"
_PUBLISHER_ID = "mycelium-release"
_DISTRIBUTION = ("ubuntu", "24.04")

_HIDDEN_IMPORTS = (
    "mycelium_a13_macos.serving",
    "mycelium_a13_macos.workflow",
    "mycelium_a13_macos.managed_observations",
    "mycelium_a13_linux.installer",
    "mycelium_a13_linux.service_install",
    "mycelium_a13_linux.managed_host.__main__",
    "mycelium_service_runner",
)

_SPEC = """\\
# Generated by scripts/build_a13_linux.py frozen-input; do not edit.
# Build on {build_host}: pyinstaller --noconfirm --clean mycelium-linux.spec
# (PyInstaller {pyinstaller}, CPython {python}, from the pinned linux wheels only.)
a = Analysis(
    ['source/mycelium_a13_macos/__main__.py'],
    pathex=['source'],
    binaries=[
        ('native/mycelium-iroh-sidecar', 'mycelium_a13_macos/native'),
        ('native/cloudflared', 'mycelium_a13_macos/native'),
    ],
    datas=[
        ('source/mycelium_a13_macos/web', 'mycelium_a13_macos/web'),
        ('native/cloudflared-LICENSE', 'third_party'),
    ],
    hiddenimports={hidden!r},
    excludes=['mlx', 'tkinter'],
    noarchive=False,
)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='mycelium', console=True, upx=False, strip=False)
coll = COLLECT(exe, a.binaries, a.datas, name='mycelium', upx=False, strip=False)
"""

_INSTALL_SH = """#!/bin/sh
# Per-user install: verifies the signed manifest and payload digest first. No root.
set -eu
HERE="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
exec "$HERE/mycelium/mycelium" --install --bundle "$HERE"
"""

_README = """\
Mycelium A13 Linux pilot bundle (owner_private_media)
=====================================================

Install for this user only (no sudo): ./install.sh
It verifies the Ed25519-signed installation-package-manifest.json and the
payload digest before writing anything, then installs into
~/.local/share/mycelium/<version>, adds a launcher (~/.local/bin/mycelium) and
an app-grid entry. Identity is created by the app, after this verification.

Running unattended (a systemd user unit) and running with nobody logged in
(loginctl linger) are separate, explicit choices made later in the app.
Uninstall: mycelium --uninstall (keeps your identity and membership state).
"""


def require_app_tree_root(root: Path = ROOT) -> dict[str, str]:
    return _build.require_app_tree_root(root, _APP_TREE_MARKERS)


def build_frozen_input(*, output_root: Path, root: Path = ROOT) -> dict[str, Any]:
    """Stage everything PyInstaller needs on the Linux build host; unsigned, offline."""
    require_app_tree_root(root)
    if output_root.exists():
        raise SystemExit("fresh_output_root_required")
    output_root.mkdir(parents=True, mode=0o700)
    source = output_root / "source"
    identity = _build.stage_files(root, source, _build.runtime_source_closure(root, _FROZEN_SEEDS, label="linux"))
    for relative in _FROZEN_DATA:
        _build.stage_data_tree(root, relative, source, identity["sha256"])
    (output_root / "native").mkdir()
    spec = _SPEC.format(build_host=BUILD_HOST, pyinstaller=PYINSTALLER_PIN, python=LINUX_PYTHON,
                        hidden=list(_HIDDEN_IMPORTS))
    (output_root / "mycelium-linux.spec").write_text(spec, encoding="utf-8")
    input_digest = "sha256:" + hashlib.sha256(
        json.dumps({"files": identity["sha256"], "spec": spec}, sort_keys=True).encode("utf-8")
    ).hexdigest()
    record = {
        "protocol": FROZEN_INPUT_PROTOCOL,
        "source_revision": _build.git_head(root),
        "input_digest": input_digest,
        "files": dict(sorted(identity["sha256"].items())),
        "pyinstaller": PYINSTALLER_PIN,
        "linux_python": LINUX_PYTHON,
        "build_host": BUILD_HOST,
        "native_inputs_required": {
            "native/mycelium-iroh-sidecar": "cargo build --release --offline --locked on the build host",
            "native/cloudflared": "linux-offline/packaging/cloudflared/cloudflared-linux-<arch>",
            "native/cloudflared-LICENSE": "linux-offline/packaging/cloudflared/LICENSE",
        },
        "signed": False,
    }
    (output_root / "package-input.json").write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    return record


def declared_service_member(work_root: Path) -> dict[str, Any]:
    """The declared user unit rendered by the shared renderer (template paths; real paths render on device)."""
    from mycelium_a13_linux.service_install import UNIT_NAME, service_config
    from mycelium_a13_linux.service_lifecycle import build_linux_service_package

    config = service_config(package_root="/home/user/.config/mycelium/service",
                            host_root="/home/user/.local/state/mycelium/host",
                            app_executable="/home/user/.local/share/mycelium/current/mycelium/mycelium")
    package = build_linux_service_package(config, package_root=work_root / "service-package",
                                          install_mode="systemd_user")
    if package["systemd_unit"]["name"] != UNIT_NAME:
        raise SystemExit("linux_service_member_not_rendered")
    return package


def finalize_linux_bundle(
    *,
    frozen_dir: Path,
    output_root: Path,
    signing_key_path: Path,
    version: str,
    architecture: str = "x86_64",
    rollback_floor: str = "0.1.0",
    issued_at: float | None = None,
    root: Path = ROOT,
) -> dict[str, Any]:
    """Lay out and sign the self-installing bundle around a frozen one-folder app."""
    import shutil
    import time

    from mycelium_a13_linux.install_source import PROTOCOL as SOURCE_PROTOCOL, validate_install_source
    from mycelium_a13_linux.installer import PAYLOAD_DIRECTORY
    from mycelium_a13_linux.package_manifest import build_linux_package_manifest
    from mycelium_a13_linux.platform_admission import ADMITTED_ARCHITECTURES

    if architecture not in ADMITTED_ARCHITECTURES:
        raise SystemExit("architecture_not_admitted")
    for relative in FROZEN_REQUIRED:
        path = frozen_dir / relative
        if path.is_symlink() or not path.is_file():
            raise SystemExit("frozen_app_incomplete:" + relative)
    if output_root.exists():
        raise SystemExit("fresh_output_root_required")
    output_root.mkdir(parents=True, mode=0o700)
    payload = output_root / PAYLOAD_DIRECTORY
    shutil.copytree(frozen_dir, payload, symlinks=True)
    digest = _build.payload_digest(payload)
    artifact_name = f"mycelium-{version}-linux-{architecture}"
    signer = _build.load_pinned_signer(signing_key_path, endpoint_id=_SIGNER_ENDPOINT_ID)
    member = declared_service_member(output_root.parent / (output_root.name + ".work"))
    distribution, distribution_version = _DISTRIBUTION
    publisher = {"publisher_id": _PUBLISHER_ID, "endpoint_id": signer.endpoint_id,
                 "verification_key_record": signer.public_key_record()}
    install_source = validate_install_source({
        "protocol": SOURCE_PROTOCOL,
        "channel": _CHANNEL,
        "package_class": "signed_linux_package",
        "artifact_name": artifact_name,
        "artifact_digest": digest,
        "publisher_identity": publisher,
        "minimum_os": f"{distribution}-{distribution_version}",
        "platform_architecture": architecture,
        "distribution_id": distribution,
        "distribution_version": distribution_version,
        "service_manager": "systemd",
        "install_mode": "systemd_user",
        "rollback_floor": rollback_floor,
        "lifecycle_support": True,
        "expert_tools_required": [],
    })
    issued = float(time.time() if issued_at is None else issued_at)
    manifest = build_linux_package_manifest(
        signer=signer, issued_at=issued, expires_at=issued + 90 * 86400,
        source_revision=_build.git_head(root) or "0" * 40,
        build_inputs={"builder_id": "mycelium-ci", "build_digest": digest},
        platform_architecture={"system": "linux", "machine": architecture,
                               "distribution_id": distribution, "distribution_version": distribution_version},
        package_digest=digest,
        publisher_identity=publisher,
        minimum_os=f"{distribution}-{distribution_version}",
        service_descriptor={"unit_name": member["systemd_unit"]["name"], "sha256": member["systemd_unit"]["sha256"],
                            "install_mode": "systemd_user", "lifecycle_support": True},
        update_channel=_CHANNEL,
        rollback_floor=rollback_floor,
        capability_protocol="mycelium.capability_report.v1",
        privacy_notice="mycelium-a13-privacy-v1",
        expiry_revocation_policy="expire_after_90d_or_revocation_list",
    )
    (output_root / "install-source.json").write_text(json.dumps(install_source, indent=2) + "\n")
    (output_root / "installation-package-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    script = output_root / "install.sh"
    script.write_text(_INSTALL_SH)
    script.chmod(0o755)
    (output_root / "README-PILOT.txt").write_text(_README)
    report = {
        "platform": f"linux-{architecture}",
        "channel": _CHANNEL,
        "signing": "Ed25519-signed manifest (no OS code-signing layer on Linux)",
        "version": version,
        "artifact_name": artifact_name,
        "payload_digest": digest,
        "install_mode": "systemd_user",
        "service_unit": {"name": member["systemd_unit"]["name"], "sha256": member["systemd_unit"]["sha256"]},
        "source_revision": _build.git_head(root),
        "manifest_publisher_key_digest": signer.verification_key_digest,
    }
    (output_root / "artifact-identity.json").write_text(json.dumps(report, indent=2) + "\n")
    sums = "".join(
        f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.name}\n"
        for path in sorted(output_root.iterdir()) if path.is_file()
    )
    (output_root / "SHA256SUMS").write_text(sums)
    tar_path = output_root.parent / (artifact_name + ".tar.gz")
    tar_raw = _build.deterministic_tar_gz(output_root, tar_path, prefix=artifact_name)
    report["tarball"] = str(tar_path)
    report["tarball_sha256"] = hashlib.sha256(tar_raw).hexdigest()
    return report


def main() -> None:
    if sys.argv[1:2] == ["frozen-input"]:
        parser = argparse.ArgumentParser(description="stage the PyInstaller input (offline, unsigned)")
        parser.add_argument("--output-root", type=Path, required=True)
        args = parser.parse_args(sys.argv[2:])
        print(json.dumps(build_frozen_input(output_root=args.output_root.expanduser().absolute())["input_digest"]))
        return
    if sys.argv[1:2] == ["finalize"]:
        parser = argparse.ArgumentParser(description="sign and lay out the self-installing bundle")
        parser.add_argument("--frozen-dir", type=Path, required=True, help="PyInstaller dist/mycelium")
        parser.add_argument("--output-root", type=Path, required=True)
        parser.add_argument("--signing-key-file", type=Path, required=True,
                            help="path to 32 raw Ed25519 private-key bytes; NEVER printed or logged")
        parser.add_argument("--version", required=True)
        parser.add_argument("--architecture", default="x86_64")
        parser.add_argument("--rollback-floor", default="0.1.0")
        args = parser.parse_args(sys.argv[2:])
        print(json.dumps(finalize_linux_bundle(
            frozen_dir=args.frozen_dir.expanduser().absolute(),
            output_root=args.output_root.expanduser().absolute(),
            signing_key_path=args.signing_key_file, version=args.version,
            architecture=args.architecture, rollback_floor=args.rollback_floor)))
        return
    raise SystemExit("usage: build_a13_linux.py frozen-input|finalize ...")


if __name__ == "__main__":
    main()
