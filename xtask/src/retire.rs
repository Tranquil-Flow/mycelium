//! `xtask retire check`: the R6 test-retirement check, by test IDs and obligations, never by counts.
//!
//! The old suite is the Python v0.1.4 inventory (`test-support/obligations/data/test-groups.json`):
//! every statically discovered test definition is the ID `py:<file>::<name>`. The new suite is every
//! Rust `#[test]` function, `rs:<path>::<module path>::<fn>`. `xtask/retirement/registry.json`
//! holds one approved row per old ID (or per old file) naming its disposition:
//!
//! * `mapped`: replaced by the listed Rust tests (consolidation = several rows, one `new`);
//! * `retired`: removed, with a reason, evidence and a rollback artifact;
//! * `external_oracle`: kept outside the product as an oracle, with a reason.
//!
//! Every row needs a known obligation, a listed approver, a real approval date and `EV-` evidence.
//! The check fails while any old ID has no valid row; how many tests exist on either side never
//! enters the decision. Dropping a test, renaming it or merging two into one all show up as IDs.
use crate::{lint::Source, policy::Date, workspace};
use serde::Deserialize;
use sha2::{Digest, Sha256};
use std::{
    collections::{BTreeMap, BTreeSet},
    env, fs,
    path::{Path, PathBuf},
};

pub(crate) fn fail(code: &str, detail: impl std::fmt::Display) -> String {
    format!("RETIRE: {code}: {detail}")
}
fn sha256_hex(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// The old (Python v0.1.4) suite inventory: statically discovered test IDs `py:<file>::<name>`.
#[derive(Debug, Clone, Default)]
pub struct Baseline {
    pub source_sha: String,
    pub sha256: String,
    pub ids: BTreeSet<String>,
    pub files: usize,
    pub support_files: usize,
    /// Every inventory file (test or support) with its number of statically discovered tests.
    pub sources: BTreeMap<String, usize>,
}
#[derive(Deserialize)]
struct RawGroup {
    source: String,
    role: String,
    source_tests: Vec<RawTest>,
}
#[derive(Deserialize)]
struct RawTest {
    name: String,
}
/// Parses `test-support/obligations/data/test-groups.json`-shaped bytes.
pub fn load_baseline(bytes: &[u8], source_sha: &str) -> Result<Baseline, String> {
    let groups: Vec<RawGroup> =
        serde_json::from_slice(bytes).map_err(|e| fail("baseline_invalid", e))?;
    let mut baseline = Baseline {
        source_sha: source_sha.to_string(),
        sha256: sha256_hex(bytes),
        ..Baseline::default()
    };
    for group in groups {
        match group.role.as_str() {
            "test_file" => baseline.files += 1,
            "support_or_fixture" => baseline.support_files += 1,
            other => {
                return Err(fail(
                    "baseline_invalid",
                    format!("{}: unknown role {other}", group.source),
                ));
            }
        }
        baseline
            .sources
            .insert(group.source.clone(), group.source_tests.len());
        for test in group.source_tests {
            let id = format!("py:{}::{}", group.source, test.name);
            if !baseline.ids.insert(id.clone()) {
                return Err(fail("baseline_duplicate_id", id));
            }
        }
    }
    Ok(baseline)
}

struct Collector<'a> {
    path: &'a str,
    modules: Vec<String>,
    ids: &'a mut BTreeSet<String>,
}
impl Collector<'_> {
    fn items(&mut self, items: &[syn::Item]) {
        for item in items {
            match item {
                syn::Item::Fn(function) if is_test(&function.attrs) => {
                    let mut id = format!("rs:{}", self.path);
                    for module in &self.modules {
                        id.push_str("::");
                        id.push_str(module);
                    }
                    id.push_str(&format!("::{}", function.sig.ident));
                    self.ids.insert(id);
                }
                syn::Item::Mod(module) => {
                    if let Some((_, inner)) = &module.content {
                        self.modules.push(module.ident.to_string());
                        self.items(inner);
                        self.modules.pop();
                    }
                }
                _ => {}
            }
        }
    }
}
fn is_test(attrs: &[syn::Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path()
            .segments
            .last()
            .is_some_and(|segment| segment.ident == "test")
    })
}
/// Rust test IDs `rs:<path>::<module path>::<fn>` for every `#[test]` (also `tokio::test`).
/// Tests generated by macros are not visible to this static discovery.
pub fn discover_rust_tests(sources: &[Source]) -> Result<BTreeSet<String>, String> {
    let mut ids = BTreeSet::new();
    for source in sources {
        let file = syn::parse_file(&source.text)
            .map_err(|e| fail("rust_parse_failed", format!("{}: {e}", source.path)))?;
        Collector {
            path: &source.path,
            modules: Vec::new(),
            ids: &mut ids,
        }
        .items(&file.items);
    }
    Ok(ids)
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Finding {
    pub code: &'static str,
    pub subject: String,
    pub detail: String,
}
#[derive(Debug, Clone, Default)]
pub struct Report {
    pub total_old: usize,
    pub resolved: usize,
    pub unresolved: BTreeSet<String>,
    pub unresolved_by_file: BTreeMap<String, usize>,
    pub findings: Vec<Finding>,
    pub rows: usize,
}
impl Report {
    /// Structure only: every row is well formed, approved and evidenced.
    pub fn structure_ok(&self) -> bool {
        self.findings.is_empty()
    }
    /// Full R6: structure ok and no old test ID is left without an approved disposition.
    pub fn ok(&self) -> bool {
        self.structure_ok() && self.unresolved.is_empty()
    }
    pub fn codes(&self) -> Vec<&'static str> {
        self.findings.iter().map(|f| f.code).collect()
    }
}
pub struct Context<'a> {
    pub baseline: &'a Baseline,
    pub obligations: &'a BTreeSet<String>,
    pub rust_tests: &'a BTreeSet<String>,
    /// When present, `EV-` evidence references must exist in this ledger id set.
    pub evidence_ids: Option<&'a BTreeSet<String>>,
    /// When present, a `mapped` row must cite evidence whose log shows each new test `ok`.
    pub test_proofs: Option<&'a Proofs>,
}

/// The Rust tests each evidence record's log shows as `ok`: only a PASS record of kind `gate`
/// with a readable log proves anything. A name is stored with the target (`tests/alpha.rs`,
/// `unittests src/lib.rs`) it ran under.
#[derive(Debug, Clone, Default)]
pub struct Proofs {
    ok: BTreeMap<String, Vec<(String, String)>>,
    /// `(fault id, catching test)` of every `FAULT-CAUGHT <fault> by <test>` line of a PASS gate log.
    caught: BTreeMap<String, Vec<(String, String)>>,
}
impl Proofs {
    /// `ledger` is `evidence.jsonl` text; relative `log` paths resolve against `base`.
    pub fn from_ledger(ledger: &str, base: &Path) -> Result<Self, String> {
        let mut ok = BTreeMap::new();
        let mut caught = BTreeMap::new();
        for (number, line) in ledger
            .lines()
            .enumerate()
            .filter(|(_, l)| !l.trim().is_empty())
        {
            let value: serde_json::Value = serde_json::from_str(line)
                .map_err(|e| fail("ledger_line_invalid", format!("line {}: {e}", number + 1)))?;
            let text = |key: &str| value.get(key).and_then(serde_json::Value::as_str);
            let (Some(id), Some("gate"), Some("PASS"), Some(log)) =
                (text("id"), text("kind"), text("verdict"), text("log"))
            else {
                continue;
            };
            let path = if Path::new(log).is_absolute() {
                PathBuf::from(log)
            } else {
                base.join(log)
            };
            let Ok(bytes) = fs::read(&path) else {
                continue;
            };
            let log = String::from_utf8_lossy(&bytes);
            ok.insert(id.to_string(), passed_tests(&log));
            caught.insert(id.to_string(), caught_faults(&log));
        }
        Ok(Self { ok, caught })
    }
    /// Does PASS record `ev` show `FAULT-CAUGHT <fault> by <test>` (the test named as in libtest)?
    pub fn shows_caught(&self, ev: &str, fault: &str, test: &str) -> bool {
        self.caught.get(ev).is_some_and(|lines| {
            lines
                .iter()
                .any(|(f, t)| f == fault && (t == test || t.ends_with(&format!("::{test}"))))
        })
    }
    /// Does record `ev` show the Rust test `new` (`rs:<path>::<modules>::<fn>`) as `ok`?
    pub fn shows(&self, ev: &str, new: &str) -> bool {
        let Some(rest) = new.strip_prefix("rs:") else {
            return false;
        };
        let Some((path, name)) = rest.split_once(".rs::") else {
            return false;
        };
        let target_needle = path
            .rsplit_once("/tests/")
            .filter(|(_, file)| !file.contains('/'))
            .map(|(_, file)| format!("tests/{file}.rs"));
        let suffix = format!("::{name}");
        self.ok.get(ev).is_some_and(|tests| {
            tests.iter().any(|(target, test)| {
                (test == name || test.ends_with(&suffix))
                    && target_needle
                        .as_ref()
                        .is_none_or(|needle| target.contains(needle.as_str()))
            })
        })
    }
}
/// `(fault, test)` for every `FAULT-CAUGHT <fault> by <test>` line: a mutation run prints it only
/// after the mutant made `<test>` fail for the intended reason (a harness crash prints nothing).
fn caught_faults(log: &str) -> Vec<(String, String)> {
    log.lines()
        .filter_map(|line| {
            let rest = line.trim().strip_prefix("FAULT-CAUGHT ")?;
            let (fault, test) = rest.split_once(" by ")?;
            let test = test.split_whitespace().next()?;
            Some((fault.trim().to_string(), test.to_string()))
        })
        .collect()
}
/// `(target, test name)` for every `test <name> ... ok` line of a libtest log.
fn passed_tests(log: &str) -> Vec<(String, String)> {
    let mut target = String::new();
    let mut found = Vec::new();
    for line in log.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("Running ") {
            target = rest.split(" (").next().unwrap_or(rest).to_string();
        } else if let Some(name) = trimmed
            .strip_prefix("test ")
            .and_then(|rest| rest.strip_suffix(" ... ok"))
        {
            found.push((target.clone(), name.to_string()));
        }
    }
    found
}

/// The evidence ledger as the TB-5 checks see it: which EV ids exist, which of them are PASS gate
/// records, and what the readable logs of those prove.
#[derive(Debug, Clone, Default)]
pub struct Ledger {
    pub ids: BTreeSet<String>,
    pub pass_gates: BTreeSet<String>,
    pub proofs: Proofs,
}
impl Ledger {
    pub fn parse(text: &str, base: &Path) -> Result<Self, String> {
        let mut ledger = Self {
            proofs: Proofs::from_ledger(text, base)?,
            ..Self::default()
        };
        for line in text.lines().filter(|l| !l.trim().is_empty()) {
            let value: serde_json::Value =
                serde_json::from_str(line).map_err(|e| fail("ledger_line_invalid", e))?;
            let text = |key: &str| value.get(key).and_then(serde_json::Value::as_str);
            if let Some(id) = text("id") {
                ledger.ids.insert(id.to_string());
                if text("kind") == Some("gate") && text("verdict") == Some("PASS") {
                    ledger.pass_gates.insert(id.to_string());
                }
            }
        }
        Ok(ledger)
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawRegistry {
    schema: u64,
    baseline: RawPin,
    approvers: Vec<String>,
    rows: Vec<RawRow>,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawPin {
    sha256: String,
    source_sha: String,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RawRow {
    old: Option<String>,
    old_file: Option<String>,
    disposition: String,
    #[serde(default)]
    new: Vec<String>,
    obligation: Option<String>,
    approver: Option<String>,
    approved: Option<String>,
    #[serde(default)]
    evidence: Vec<String>,
    reason: Option<String>,
    rollback: Option<String>,
    #[serde(default)]
    mutation_verified: bool,
    kill_matrix: Option<String>,
}

pub(crate) fn present(value: &Option<String>) -> bool {
    value.as_deref().is_some_and(|s| !s.trim().is_empty())
}
/// `EV-<8 digits>-<4 or more digits>`.
pub fn is_evidence_id(text: &str) -> bool {
    let Some(rest) = text.strip_prefix("EV-") else {
        return false;
    };
    let Some((date, sequence)) = rest.split_once('-') else {
        return false;
    };
    date.len() == 8
        && date.bytes().all(|b| b.is_ascii_digit())
        && sequence.len() >= 4
        && sequence.bytes().all(|b| b.is_ascii_digit())
}
pub fn file_of(id: &str) -> &str {
    let rest = id.strip_prefix("py:").unwrap_or(id);
    rest.split("::").next().unwrap_or(rest)
}

fn row_findings(
    index: usize,
    row: &RawRow,
    approvers: &BTreeSet<&str>,
    context: &Context,
) -> Vec<Finding> {
    let subject = row
        .old
        .clone()
        .or_else(|| row.old_file.clone())
        .unwrap_or_else(|| format!("row {index}"));
    let mut found = Vec::new();
    let mut add = |code: &'static str, detail: String| {
        found.push(Finding {
            code,
            subject: subject.clone(),
            detail,
        });
    };
    match row.disposition.as_str() {
        "mapped" => {
            if row.new.is_empty() {
                add("new_missing", "a mapped row names its Rust tests".into());
            }
            for new in &row.new {
                if !context.rust_tests.contains(new) {
                    add("new_test_unknown", format!("no such Rust test: {new}"));
                } else if let Some(proofs) = context.test_proofs
                    && !row.evidence.iter().any(|ev| proofs.shows(ev, new))
                {
                    add(
                        "new_test_not_proved",
                        format!("no cited PASS gate log shows `{new}` ok"),
                    );
                }
            }
        }
        "retired" => {
            if !present(&row.reason) {
                add("reason_missing", "a retirement states why".into());
            }
            if !present(&row.rollback) {
                add(
                    "rollback_missing",
                    "a retirement names its rollback artifact".into(),
                );
            }
        }
        "external_oracle" => {
            if !present(&row.reason) {
                add("reason_missing", "an external oracle states why".into());
            }
        }
        other => add(
            "disposition_invalid",
            format!("{other}: mapped, retired or external_oracle"),
        ),
    }
    match row.obligation.as_deref() {
        None | Some("") => add("obligation_missing", "every row names an obligation".into()),
        Some(id) if !context.obligations.contains(id) => {
            add("obligation_unknown", format!("not in the registry: {id}"));
        }
        Some(_) => {}
    }
    match row.approver.as_deref() {
        None | Some("") => add("approver_missing", "every row is approved".into()),
        Some(who) if !approvers.contains(who) => add(
            "approver_unknown",
            format!("{who} is not one of the registry's approvers"),
        ),
        Some(_) => {}
    }
    if row
        .approved
        .as_deref()
        .is_none_or(|date| Date::parse(date).is_err())
    {
        add(
            "approved_invalid",
            "approved is a real YYYY-MM-DD date".into(),
        );
    }
    if row.evidence.is_empty() {
        add("evidence_missing", "cite at least one EV record".into());
    }
    for reference in &row.evidence {
        if !is_evidence_id(reference) {
            add(
                "evidence_malformed",
                format!("{reference:?} is not an EV-yyyymmdd-nnnn id"),
            );
        } else if context
            .evidence_ids
            .is_some_and(|ids| !ids.contains(reference))
        {
            add(
                "evidence_unknown",
                format!("{reference} is not in the ledger"),
            );
        }
    }
    if row.mutation_verified
        && !row.kill_matrix.as_deref().is_some_and(|id| {
            is_evidence_id(id) && context.evidence_ids.is_none_or(|s| s.contains(id))
        })
    {
        add(
            "mutation_unproven",
            "mutation_verified needs a kill_matrix EV record".into(),
        );
    }
    found
}

pub fn check(registry_json: &str, context: &Context) -> Result<Report, String> {
    let raw: RawRegistry =
        serde_json::from_str(registry_json).map_err(|e| fail("registry_invalid", e))?;
    if raw.schema != 1 {
        return Err(fail("registry_invalid", "schema must be 1"));
    }
    let baseline = context.baseline;
    let mut report = Report {
        total_old: baseline.ids.len(),
        rows: raw.rows.len(),
        ..Report::default()
    };
    let mut pinned = true;
    if raw.baseline.sha256 != baseline.sha256 {
        pinned = false;
        report.findings.push(Finding {
            code: "baseline_pin_mismatch",
            subject: "baseline".into(),
            detail: format!(
                "registry pins {}, the inventory is {}",
                raw.baseline.sha256, baseline.sha256
            ),
        });
    }
    if raw.baseline.source_sha != baseline.source_sha {
        pinned = false;
        report.findings.push(Finding {
            code: "baseline_source_mismatch",
            subject: "baseline".into(),
            detail: format!(
                "registry names source {}, the inventory is {}",
                raw.baseline.source_sha, baseline.source_sha
            ),
        });
    }
    let approvers: BTreeSet<&str> = raw.approvers.iter().map(String::as_str).collect();
    let mut claimed: BTreeSet<String> = BTreeSet::new();
    let mut resolved: BTreeSet<String> = BTreeSet::new();
    for (index, row) in raw.rows.iter().enumerate() {
        let mut found = row_findings(index, row, &approvers, context);
        let covered: Vec<String> = match (&row.old, &row.old_file) {
            (Some(id), None) => {
                if baseline.ids.contains(id) {
                    vec![id.clone()]
                } else {
                    found.push(Finding {
                        code: "old_id_unknown",
                        subject: id.clone(),
                        detail: "not in the baseline inventory".into(),
                    });
                    Vec::new()
                }
            }
            (None, Some(file)) => {
                let ids: Vec<String> = baseline
                    .ids
                    .iter()
                    .filter(|id| file_of(id) == file)
                    .cloned()
                    .collect();
                if ids.is_empty() {
                    found.push(Finding {
                        code: "old_file_unknown",
                        subject: file.clone(),
                        detail: "no test of that file in the baseline inventory".into(),
                    });
                }
                ids
            }
            _ => {
                found.push(Finding {
                    code: "row_shape_invalid",
                    subject: format!("row {index}"),
                    detail: "name exactly one of old and old_file".into(),
                });
                Vec::new()
            }
        };
        for id in &covered {
            if !claimed.insert(id.clone()) {
                found.push(Finding {
                    code: "old_id_duplicate",
                    subject: id.clone(),
                    detail: "claimed by more than one row".into(),
                });
            }
        }
        if found.is_empty() && pinned {
            resolved.extend(covered);
        }
        report.findings.extend(found);
    }
    report.resolved = resolved.len();
    report.unresolved = baseline.ids.difference(&resolved).cloned().collect();
    for id in &report.unresolved {
        *report
            .unresolved_by_file
            .entry(file_of(id).to_string())
            .or_default() += 1;
    }
    Ok(report)
}

