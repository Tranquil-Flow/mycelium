const USAGE: &str = "USAGE: xtask retire check [--schema 1|2] [--baseline FILE] [--baseline-source-sha SHA] [--registry FILE] [--obligations FILE] [--root DIR] [--ledger FILE] [--structure-only]\n  schema 2 (default) also: [--behaviours FILE] [--faults FILE] [--dispositions FILE] [--tb4-dir DIR] [--catches FILE] [--policy FILE] [--registry-dir DIR] [--full]";
/// How many unresolved IDs / files the report prints before summarising the rest.
const LIST_LIMIT: usize = 20;

pub(crate) fn read(path: &Path) -> Result<Vec<u8>, String> {
    fs::read(path).map_err(|e| {
        fail(
            "input_unreadable",
            format!("{}: {:?}", path.display(), e.kind()),
        )
    })
}
fn ledger_ids(path: &Path) -> Result<BTreeSet<String>, String> {
    let text = String::from_utf8_lossy(&read(path)?).to_string();
    let mut ids = BTreeSet::new();
    for (number, line) in text
        .lines()
        .enumerate()
        .filter(|(_, l)| !l.trim().is_empty())
    {
        let value: serde_json::Value = serde_json::from_str(line).map_err(|e| {
            fail(
                "ledger_line_invalid",
                format!("{}:{}: {e}", path.display(), number + 1),
            )
        })?;
        if let Some(id) = value.get("id").and_then(serde_json::Value::as_str) {
            ids.insert(id.to_string());
        }
    }
    Ok(ids)
}

/// Options shared by `retire check` and `behaviours check`.
pub(crate) const VALUE_OPTIONS: [&str; 14] = [
    "--schema",
    "--baseline",
    "--baseline-source-sha",
    "--registry",
    "--obligations",
    "--root",
    "--ledger",
    "--behaviours",
    "--faults",
    "--dispositions",
    "--tb4-dir",
    "--catches",
    "--policy",
    "--registry-dir",
];
pub(crate) struct Options {
    pub values: BTreeMap<&'static str, String>,
    pub structure_only: bool,
    pub full: bool,
}
pub(crate) fn parse_options(args: &[String], allow_full: bool) -> Result<Options, String> {
    let mut options = Options {
        values: BTreeMap::new(),
        structure_only: false,
        full: false,
    };
    let mut rest = args.iter();
    while let Some(arg) = rest.next() {
        match arg.as_str() {
            "--structure-only" if !options.structure_only => options.structure_only = true,
            "--full" if allow_full && !options.full => options.full = true,
            key if VALUE_OPTIONS.contains(&key) => {
                let key = VALUE_OPTIONS
                    .iter()
                    .find(|k| **k == key)
                    .copied()
                    .unwrap_or_default();
                let value = rest
                    .next()
                    .ok_or_else(|| format!("USAGE: {key} needs a value\n{USAGE}"))?;
                if options.values.insert(key, value.clone()).is_some() {
                    return Err(format!("USAGE: repeated option {key}\n{USAGE}"));
                }
            }
            other => {
                return Err(format!(
                    "USAGE: unknown or repeated option {other}\n{USAGE}"
                ));
            }
        }
    }
    Ok(options)
}
pub(crate) fn root_of(options: &Options) -> PathBuf {
    options.values.get("--root").map_or_else(
        || {
            PathBuf::from(env!("CARGO_MANIFEST_DIR"))
                .parent()
                .map_or_else(|| PathBuf::from("."), Path::to_path_buf)
        },
        PathBuf::from,
    )
}
/// The schema-1 inputs, loaded and checked: the Python inventory, the per-id registry, the Rust
/// tests and the evidence ledger.
pub(crate) struct Schema1 {
    pub baseline: Baseline,
    pub report: Report,
    pub rust_tests: BTreeSet<String>,
    pub ledger: Option<Ledger>,
}
pub(crate) fn load_schema1(options: &Options, root: &Path) -> Result<Schema1, String> {
    let data = root.join("test-support/obligations/data");
    let baseline_path = options
        .values
        .get("--baseline")
        .map_or_else(|| data.join("test-groups.json"), PathBuf::from);
    let sibling = baseline_path
        .parent()
        .map_or_else(|| PathBuf::from("."), Path::to_path_buf);
    let source_sha = match options.values.get("--baseline-source-sha") {
        Some(sha) => sha.clone(),
        None => {
            let meta: serde_json::Value =
                serde_json::from_slice(&read(&sibling.join("baseline.json"))?)
                    .map_err(|e| fail("baseline_invalid", e))?;
            meta.get("source_sha")
                .and_then(serde_json::Value::as_str)
                .ok_or_else(|| fail("baseline_invalid", "baseline.json has no source_sha"))?
                .to_string()
        }
    };
    let baseline = load_baseline(&read(&baseline_path)?, &source_sha)?;
    let obligations_path = options
        .values
        .get("--obligations")
        .map_or_else(|| sibling.join("obligations.json"), PathBuf::from);
    let obligations: BTreeSet<String> =
        serde_json::from_slice::<Vec<serde_json::Value>>(&read(&obligations_path)?)
            .map_err(|e| fail("obligations_invalid", e))?
            .iter()
            .filter_map(|row| row.get("id").and_then(serde_json::Value::as_str))
            .map(str::to_string)
            .collect();
    let registry_path = options.values.get("--registry").map_or_else(
        || root.join("xtask/retirement/registry.json"),
        PathBuf::from,
    );
    let registry = String::from_utf8_lossy(&read(&registry_path)?).to_string();
    let rust_tests = discover_rust_tests(&workspace::sources(root)?)?;
    let ledger_path = options.values.get("--ledger").map(PathBuf::from);
    let evidence = ledger_path.as_deref().map(ledger_ids).transpose()?;
    let ledger = ledger_path
        .as_deref()
        .map(|ledger| {
            Ledger::parse(
                &String::from_utf8_lossy(&read(ledger)?),
                ledger.parent().unwrap_or(Path::new(".")),
            )
        })
        .transpose()?;
    let report = check(
        &registry,
        &Context {
            baseline: &baseline,
            obligations: &obligations,
            rust_tests: &rust_tests,
            evidence_ids: evidence.as_ref(),
            test_proofs: ledger.as_ref().map(|l| &l.proofs),
        },
    )?;
    Ok(Schema1 {
        baseline,
        report,
        rust_tests,
        ledger,
    })
}

/// `xtask retire ...` entry point. Exit codes: 0 resolved (or structure ok with
/// `--structure-only`), 1 findings or unresolved, 2 unreadable or malformed input.
/// `--schema 1` is the per-test-id check; schema 2 (default) resolves test groups.
pub fn cli(args: &[String]) -> Result<u8, String> {
    if args.first().map(String::as_str) != Some("check") {
        return Err(format!("USAGE: unknown retire subcommand\n{USAGE}"));
    }
    let options = parse_options(&args[1..], true)?;
    match options.values.get("--schema").map(String::as_str) {
        None | Some("2") => return crate::groups::cli(&options),
        Some("1") if !options.full => {}
        Some(other) => {
            return Err(format!("USAGE: unsupported --schema {other}\n{USAGE}"));
        }
    }
    let root = root_of(&options);
    let structure_only = options.structure_only;
    let Schema1 {
        baseline,
        report,
        rust_tests,
        ..
    } = load_schema1(&options, &root)?;
    println!(
        "retire: {} old test IDs: {} resolved, {} unresolved ({} rows; {} Rust tests discovered; inventory sha256 {} @ source {}; {} test files, {} support files)",
        report.total_old,
        report.resolved,
        report.unresolved.len(),
        report.rows,
        rust_tests.len(),
        &baseline.sha256[..12],
        baseline.source_sha.chars().take(8).collect::<String>(),
        baseline.files,
        baseline.support_files
    );
    for finding in &report.findings {
        println!(
            "FINDING {} {}: {}",
            finding.code, finding.subject, finding.detail
        );
    }
    if !report.unresolved.is_empty() {
        let files: Vec<String> = report
            .unresolved_by_file
            .iter()
            .take(LIST_LIMIT)
            .map(|(file, n)| format!("{file}={n}"))
            .collect();
        let more = report.unresolved_by_file.len().saturating_sub(LIST_LIMIT);
        println!(
            "unresolved by file: {}{}",
            files.join(", "),
            if more > 0 {
                format!(", and {more} more files")
            } else {
                String::new()
            }
        );
        for id in report.unresolved.iter().take(LIST_LIMIT) {
            println!("  unresolved {id}");
        }
    }
    if structure_only {
        println!(
            "STRUCTURE-ONLY: rows checked; unresolved old IDs were not judged. This is not an R6 pass."
        );
        return Ok(u8::from(!report.structure_ok()));
    }
    Ok(u8::from(!report.ok()))
}
