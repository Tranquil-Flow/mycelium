class Svgs(HTMLParser):
    def __init__(self):
        super().__init__()
        self.ids, self.svgs, self.figs, self.panel, self.bad = [], [], [], None, []
        self.cur = None

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if 'id' in a:
            self.ids.append(a['id'])
        if 'data-panel' in a:
            self.panel = a['data-panel']
        if tag == 'figure':
            self.figs.append((self.panel, a.get('data-fig')))
        if tag == 'svg':
            self.cur = dict(a, panel=self.panel, fig=self.figs[-1][1], titles=[], texts=[])
            self.svgs.append(self.cur)
        if self.cur is not None:
            if 'style' in a or tag in ('style', 'script', 'image', 'foreignobject', 'a', 'use'):
                self.bad.append((tag, a))
            for k, v in a.items():
                if k in ('href', 'xlink:href', 'src') or (v and re.search(r'url\((?!#)', v)):
                    self.bad.append((tag, k, v))
        self._tag = tag

    def handle_endtag(self, tag):
        if tag == 'svg':
            self.cur = None

    def handle_data(self, data):
        if self.cur is not None and data.strip():
            (self.cur['titles'] if self._tag in ('title', 'desc') else self.cur['texts']).append(data.strip())


def test_illustrations_are_inline_accessible_and_self_contained():
    page = html()
    p = Svgs()
    p.feed(page)
    assert p.figs == [('simple', 'model-split'), ('simple', 'swarm'),
                      ('technical', 'pipeline'), ('technical', 'stack')]
    assert len(p.ids) == len(set(p.ids)), 'ids are unique on the page'
    assert not p.bad, p.bad
    assert len(p.svgs) == 8
    for svg in p.svgs:
        assert svg['role'] == 'img' and svg['focusable'] == 'false', svg['fig']
        assert svg['data-variant'] in ('wide', 'narrow')
        w, h = int(svg['width']), int(svg['height'])
        assert svg['viewbox'] == '0 0 %d %d' % (w, h)
        title = re.search(r'<title id="%s">(.*?)</title>' % svg['aria-labelledby'], page).group(1)
        assert title == TITLES[svg['fig']]
        assert re.search(r'<desc id="%s">.{80,}</desc>' % svg['aria-describedby'], page)
    for panel, figs in FIGURES.items():
        for fig in figs:
            body = section(SECTIONS[fig])
            assert 'data-fig="%s"' % fig in body
            caption = re.search(r'data-fig="%s".*?<figcaption>(.*?)</figcaption>' % fig, page, re.S).group(1)
            assert len(caption) > 40
    # Labels inside the art keep the copy rules too.
    labels = ' '.join(t for svg in p.svgs for t in svg['texts'])
    assert 'Mac' not in labels and 'Apple' not in labels and 'token' not in labels.lower()
    assert not any(svg['fig'] == 'stages' for svg in p.svgs), 'owner removed the stages figure'
    stack_labels = [t for svg in p.svgs if svg['fig'] == 'stack' and svg['data-variant'] == 'wide' for t in svg['texts']]
    assert stack_labels[-3:] == ['Mycelium', 'compute', 'Built: early preview'] and 'Planned' in stack_labels
    # Each illustration stays bounded markup: about.html stays a reasonable page.
    assert len(page.encode()) < 260_000


