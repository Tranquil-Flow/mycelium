FIG_INFO = """(mode)=>{const panel=document.querySelector(`[data-panel=${mode}]`);
  return [...panel.querySelectorAll('figure.vision-fig')].map(fig=>{
    const shown=[...fig.querySelectorAll('svg.fig-art')].filter(s=>getComputedStyle(s).display!=='none');
    const svg=shown[0], r=svg.getBoundingClientRect(), f=fig.getBoundingClientRect(), vb=svg.viewBox.baseVal;
    const k=r.width/vb.width;
    const texts=[...svg.querySelectorAll('text')].map(t=>{const b=t.getBBox();const q=t.getBoundingClientRect();
      return {t:t.textContent, inside:b.x>=-0.5&&b.y>=-0.5&&b.x+b.width<=vb.width+0.5&&b.y+b.height<=vb.height+0.5,
              px:parseFloat(getComputedStyle(t).fontSize)*k, box:[q.left,q.top,q.right,q.bottom]}});
    const overlap=[];for(let i=0;i<texts.length;i++)for(let j=i+1;j<texts.length;j++){const a=texts[i].box,b=texts[j].box;
      if(a[0]<b[2]-1&&b[0]<a[2]-1&&a[1]<b[3]-1&&b[1]<a[3]-1)overlap.push([texts[i].t,texts[j].t])}
    return {fig:fig.dataset.fig, shown:shown.length, variant:svg.dataset.variant,
            aspect:Math.abs(r.width/r.height-vb.width/vb.height)<0.01, inFig:r.left>=f.left-0.5&&r.right<=f.right+0.5,
            inView:f.left>=-0.5&&f.right<=innerWidth+0.5, texts, overlap}})}"""


@pytest.mark.parametrize('width,height', [(390, 844), (768, 1000), (1440, 900)])
def test_illustrations_fit_read_and_have_accessible_names(directory, width, height):
    with sync_playwright() as p:
        browser = p.chromium.launch()
        for theme in ('dark', 'light'):
            page = new_page(browser, directory, width=width, height=height, theme=theme)
            for mode, figs in FIGURES.items():
                page.goto(directory.origin + '/about#' + mode)
                page.wait_for_timeout(600)
                info = page.evaluate(FIG_INFO, mode)
                assert [i['fig'] for i in info] == figs
                for i in info:
                    assert i['shown'] == 1 and i['variant'] == ('narrow' if width <= 820 else 'wide'), (width, i['fig'])
                    assert i['aspect'] and i['inFig'] and i['inView'], (width, i)
                    assert not i['overlap'], (width, i['fig'], i['overlap'])
                    for t in i['texts']:
                        assert t['inside'], (width, i['fig'], t)
                        assert t['px'] >= 11.5, (width, i['fig'], t['t'], t['px'])
                    name = TITLES[i['fig']]
                    expect(page.get_by_role('img', name=name, exact=True)).to_have_count(1)
                    expect(page.get_by_role('img', name=name, exact=True)).to_be_visible()
                assert page.evaluate('document.documentElement.scrollWidth') <= width
                assert sum(page.evaluate('window.__cls')) == 0
            assert page.outside == [], page.outside
            page.context.close()
        browser.close()


HIDE_SVG_TEXT_FILL = ".fig-art text{fill:transparent!important}"


@pytest.mark.parametrize('theme', ['dark', 'light'])
@pytest.mark.parametrize('glow', ['green', 'blue'])
@pytest.mark.parametrize('width,height', [(390, 844), (1440, 900)])
def test_illustration_labels_have_contrast_on_their_actual_pixels(directory, theme, glow, width, height):
    """Label glyphs vs the pixels around them (the art and the label halo), per label."""
    worst = []
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = new_page(browser, directory, width=width, height=height, theme=theme, glow=glow, bypass_csp=True)
        for mode, figs in FIGURES.items():
            page.goto(directory.origin + '/about#' + mode)
            page.wait_for_timeout(600)
            for fig in figs:
                loc = page.locator('figure[data-fig="%s"]' % fig)
                # Centre the figure: 'if needed' can leave its last label row just below the fold.
                loc.evaluate("e=>e.scrollIntoView({block:'center'})")
                page.wait_for_timeout(150)
                labels = page.evaluate("""(f)=>[...document.querySelectorAll(`figure[data-fig="${f}"] svg.fig-art`)]
                  .filter(s=>getComputedStyle(s).display!=='none')
                  .flatMap(s=>[...s.querySelectorAll('text')]).map(t=>{const r=t.getBoundingClientRect();
                    return {t:t.textContent,c:getComputedStyle(t).fill.match(/[\\d.]+/g).map(Number).slice(0,3),
                            r:[r.left,r.top,r.width,r.height]}})""", fig)
                assert labels or fig == 'swarm', fig
                if not labels:
                    continue
                shown = np.asarray(Image.open(io.BytesIO(page.screenshot())).convert('RGB')).astype(int)
                handle = page.add_style_tag(content=HIDE_SVG_TEXT_FILL)
                page.wait_for_timeout(100)
                backdrop = np.asarray(Image.open(io.BytesIO(page.screenshot())).convert('RGB')).astype(int)
                handle.evaluate('e=>e.remove()')
                glyph = np.abs(shown - backdrop).sum(axis=2) > 24
                dil = glyph.copy()
                for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    dil |= np.roll(glyph, (dy, dx), axis=(0, 1))
                for lab in labels:
                    x, y, w, h = lab['r']
                    x0, y0, x1, y1 = max(0, int(x)), max(0, int(y)), min(width, int(x + w + 1)), min(height, int(y + h + 1))
                    m = dil[y0:y1, x0:x1]
                    assert m.any(), (fig, lab['t'])
                    r = _ratio(np.asarray(lab['c']), backdrop[y0:y1, x0:x1][m]).min()
                    worst.append((float(r), fig, lab['t']))
        page.context.close()
        browser.close()
    worst.sort()
    print('worst label contrast', theme, glow, width, worst[:2])
    assert worst and worst[0][0] >= 4.5, worst[:5]


