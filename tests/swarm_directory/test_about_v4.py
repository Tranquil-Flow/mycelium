def section(name):
    m = re.search(r'<section class="sect" aria-labelledby="%s"[^>]*>(.*?)</section>' % name, html(), re.S)
    assert m, name
    return m.group(1)


def text(fragment):
    fragment = re.sub(r'<svg.*?</svg>', ' ', fragment, flags=re.S)
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', fragment)).replace(' ,', ',').replace(' .', '.').strip()


